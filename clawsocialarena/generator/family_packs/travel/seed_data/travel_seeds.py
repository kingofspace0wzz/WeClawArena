"""Travel-pack task seeds for the CU-D-travel and MG-C-travel cells.

Each :class:`TravelTaskSeed` carries the metadata one base task needs:
trip id, destination, dates, room/quantity target, bargaining bounds,
loyalty tier, delegated-closing authorization, and a ``lift_id``
pointer into ``travelbench_lifts.json`` for the persona/preference
context. MG seeds also carry ``co_traveler_lift_ids`` (so each
co-traveler agent can be seeded from a distinct lift), a group budget
envelope, and a consensus threshold.

Rich filesystem and database resources are NOT baked into the seed;
they are generated by the materializer (Task 4) from per-role
resource templates, with seed values substituted into a small set of
placeholders. This keeps the seed file small and lets resource
content evolve without churning the seed table.
"""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class TravelTaskSeed:
    """Metadata for one travel base task.

    Bargaining bounds (``target_unit_rate``, ``partner_floor_rate``)
    must satisfy ``partner_floor_rate < target_unit_rate`` so the
    negotiation has a non-empty bargaining zone.

    For MG-C-travel seeds, ``co_traveler_lift_ids`` lists exactly
    three TravelBench lift_ids (one per co-traveler agent). These
    lifts must exist in ``travelbench_lifts.json`` and should differ
    from the organizer's own ``lift_id`` so each co-traveler carries
    distinct private constraints.
    """

    trip_id: str
    cell_id: str
    resource_profile: str
    destination: str
    date_window: tuple[str, str]
    target_unit_rate: float
    partner_floor_rate: float
    room_type_target: str
    quantity: int
    required_terms: tuple[str, ...]
    traveler_loyalty_tier: str
    delegate_authorization_code: str
    lift_id: str
    co_traveler_lift_ids: tuple[str, ...] = field(default_factory=tuple)
    group_budget_envelope: float | None = None
    per_person_cap: float | None = None
    consensus_threshold: int | None = None


